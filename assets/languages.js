(function () {
  const selector = document.getElementById('site-language');
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('script,style,select,.language-picker')) continue;
    const original = node.nodeValue;
    const key = original.trim();
    if (translations[key]) nodes.push({node, original, key});
  }
  function applyLanguage(language) {
    if (!['en','es','th','zh-CN'].includes(language)) language = 'en';
    nodes.forEach(({node,original,key}) => {
      node.nodeValue = language === 'en' ? original : original.replace(key, translations[key][language]);
    });
    document.documentElement.lang = language;
    selector.value = language;
    const labels = {en:'Choose language',es:'Elegir idioma',th:'เลือกภาษา','zh-CN':'选择语言'};
    selector.setAttribute('aria-label', labels[language]);
    document.title = {en:'Momo Kids Lab — Learning games for curious kids',es:'Momo Kids Lab — Juegos para niños curiosos',th:'Momo Kids Lab — เกมเรียนรู้สำหรับเด็กช่างสงสัย','zh-CN':'Momo Kids Lab — 为好奇的孩子设计的学习游戏'}[language];
    try { localStorage.setItem('momo-site-language',language); } catch (_) {}
  }
  selector.addEventListener('change', () => applyLanguage(selector.value));
  let saved = 'en';
  try { saved = localStorage.getItem('momo-site-language') || 'en'; } catch (_) {}
  applyLanguage(saved);
})();
